# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases

_database_url = os.environ.get('DJANGO_DATABASE_URL', '').strip()
if not DEBUG and not _database_url:
    raise ImproperlyConfigured('DJANGO_DATABASE_URL doit désigner PostgreSQL en production.')

if _database_url:
    try:
        _database = urlsplit(_database_url)
        _database_port = _database.port
        _database_conn_max_age = int(os.environ.get('DJANGO_DB_CONN_MAX_AGE', '60'))
    except ValueError as error:
        raise ImproperlyConfigured('DJANGO_DATABASE_URL, son port ou DJANGO_DB_CONN_MAX_AGE est invalide.') from error
    if _database.scheme not in {'postgres', 'postgresql'} or not _database.path.strip('/'):
        raise ImproperlyConfigured('DJANGO_DATABASE_URL doit être une URL PostgreSQL valide.')
    if _database_conn_max_age < 0:
        raise ImproperlyConfigured('DJANGO_DB_CONN_MAX_AGE ne peut pas être négatif.')

    _database_query = parse_qs(_database.query)
    _database_options = {
        key: _database_query[key][-1]
        for key in ('sslmode', 'connect_timeout', 'application_name')
        if key in _database_query
    }
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': unquote(_database.path.lstrip('/')),
            'USER': unquote(_database.username or ''),
            'PASSWORD': unquote(_database.password or ''),
            'HOST': _database.hostname or '',
            'PORT': _database_port or '',
            'CONN_MAX_AGE': _database_conn_max_age,
            'CONN_HEALTH_CHECKS': True,
            'OPTIONS': _database_options,
        },
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


